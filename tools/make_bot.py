#!/usr/bin/env python3
"""make_bot.py route.json out.c - the demo bot's waypoints as C.

Uses the route's 'waypoints' (tools/refine_route.py) when present.

The route (from plan_route.py) is a 16-unit grid path; this keeps the
corners (Ramer-Douglas-Peucker, 6 units in x/y) and every change of floor
height, so the bot steers smoothly between fewer points.
"""
import json
import math
import sys


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    n = math.hypot(dx, dy) or 1.0
    best, bi = -1, 0
    for i in range(1, len(pts) - 1):
        p = pts[i]
        d = abs(dy * (p[0] - a[0]) - dx * (p[1] - a[1])) / n
        if abs(p[2] - a[2]) > 20 and abs(p[2] - b[2]) > 20:
            d = max(d, eps * 2)          # keep where the floor height changes
        if d > best:
            best, bi = d, i
    if best <= eps:
        return [a, b]
    return rdp(pts[:bi + 1], eps)[:-1] + rdp(pts[bi:], eps)


def main():
    route = json.load(open(sys.argv[1]))
    pts = [tuple(p) for p in route['path']]
    jumps = set(tuple(p) for p in route.get('jumps', []))
    if 'waypoints' in route:            # refined by tools/refine_route.py
        keep = [tuple(p) for p in route['waypoints']]
    else:
        keep = rdp(pts, 6.0)
    with open(sys.argv[2], 'w') as f:
        f.write('/* generated by tools/make_bot.py from %s */\n' % sys.argv[1])
        f.write('#include "bot.h"\n\nconst bot_wp_t bot_route[] = {\n')
        for p in keep[1:]:
            flags = int(p[3]) if len(p) > 3 else (1 if tuple(p) in jumps else 0)
            f.write('    { %d, %d, %d, %d },\n' % (round(p[0]), round(p[1]), round(p[2]), flags))
        f.write('};\nconst int bot_nroute = %d;\n' % (len(keep) - 1))
    print('%d route points -> %d waypoints' % (len(pts), len(keep) - 1))


if __name__ == '__main__':
    main()
