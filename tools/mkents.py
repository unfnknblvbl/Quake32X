#!/usr/bin/env python3
"""
mkents.py - game data for the level blob: entities, flat-coloured models
and sounds (used by mkmap.py).

The class, model and sound lists below define the numbering the engine
uses; `mkents.py --header src/g_ids.h` writes the matching C header.

Formats (all big-endian unless mkmap runs with --le):

  entity record, 16 bytes:
    u8 cls, u8 variant, i16 angle (degrees), i16 org[3], i16 half[3] (triggers), i16 pad

  model (offsets relative to the model's start):
    u16 numverts, numtris, numframes, numskins
    i32 scale[3], origin[3]       16.16: vertex = byte * scale + origin
    i16 radius, flags             flags: 8 = rotates (Quake's EF_ROTATE)
    u32 tris_ofs, colors_ofs, frames_ofs, normals_ofs(unused: 0)
    tris:   numtris x { u8 v0, v1, v2, pad }
    colors: numskins x numtris bytes: one palette colour per triangle,
            the average of the skin texels the triangle covers
    frames: numframes x numverts x { u8 x, y, z, normal index }

  sound table: count x { u32 offset (from the blob start), u32 length };
    data is 8-bit unsigned PCM at 11025 Hz
"""
